INSERT INTO administracionzonal.checklist (id_checklist, nombre)
SELECT configuracion.id_checklist, configuracion.nombre
FROM administracionzonal.checklist_configuracion configuracion
WHERE NOT EXISTS (
    SELECT 1
    FROM administracionzonal.checklist existente
    WHERE existente.id_checklist = configuracion.id_checklist
);

UPDATE administracionzonal.checklist_configuracion seleccion
SET siguiente_checklist_id = vinculacion.id_checklist
FROM administracionzonal.checklist_configuracion vinculacion
WHERE seleccion.codigo = 'INGRESO_SELECCION'
  AND vinculacion.codigo = 'INGRESO_VINCULACION';

DO $$
DECLARE
    secuencia_checklist text;
BEGIN
    secuencia_checklist := pg_get_serial_sequence(
        'administracionzonal.checklist',
        'id_checklist'
    );
    IF secuencia_checklist IS NOT NULL THEN
        PERFORM setval(
            secuencia_checklist,
            COALESCE((SELECT MAX(id_checklist) FROM administracionzonal.checklist), 1),
            true
        );
    END IF;
END;
$$;

