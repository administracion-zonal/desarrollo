    codigo varchar(64) NOT NULL UNIQUE,
    tipo varchar(32) NOT NULL,
    nombre varchar(160) NOT NULL,
    orden smallint NOT NULL,
    siguiente_checklist_id bigint REFERENCES administracionzonal.checklist_configuracion(id_checklist)
);

SELECT setval(
    pg_get_serial_sequence('administracionzonal.checklist_configuracion', 'id_checklist'),
    GREATEST(
        COALESCE((SELECT MAX(id_checklist) FROM administracionzonal.checklist_detalle), 0),
        COALESCE((SELECT MAX(id_checklist) FROM administracionzonal.checklist), 0),
        COALESCE((SELECT MAX(id_checklist) FROM administracionzonal.usuario_proceso), 0),
        COALESCE((SELECT MAX(id_checklist) FROM administracionzonal.checklist_configuracion), 0)
    ) + 1,
    false
);

